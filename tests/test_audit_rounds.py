"""`rounds.py` scores the Findings rounds measure from a PR's comments.

The script runs as a command, as the audit runs it. The comments are made up.
"""

import json
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "plugins" / "craft" / "skills" / "audit" / "scripts" / "rounds.py"
NO_DATA = {
    "status": "no data",
    "values": {"Rounds until PASS": None, "Blocking per round": None},
}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def review(verdict: str) -> str:
    """Return a review comment that ends with a verdict line and the footer."""
    return f"## Blocking\n\nNone.\n\n{verdict}{FOOTER}"


def rounds(tmp_path: Path, *bodies: str) -> dict[str, Any]:
    """Run `rounds.py` on comments with these bodies, and return its JSON."""
    path = tmp_path / "comments.json"
    comments = [
        {"body": body, "created_at": f"2026-11-20T10:{i:02d}:00Z"}
        for i, body in enumerate(bodies)
    ]
    path.write_text(json.dumps(comments), encoding="utf-8")
    done = subprocess.run(  # noqa: S603
        [sys.executable, str(SCRIPT), str(path)],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(done.stdout)


# Criterion 8: rounds and blocking findings.


def test_one_pass_is_one_round(tmp_path: Path) -> None:
    """A PR that passed in its full review."""
    out = rounds(tmp_path, review("PASS — 0 blocking, 2 non-blocking"))
    assert out == {
        "status": "PASS",
        "values": {"Rounds until PASS": 1, "Blocking per round": 0.0},
    }


def test_rounds_count_up_to_the_first_pass(tmp_path: Path) -> None:
    """Follow-up verdict lines count, and later comments do not."""
    out = rounds(
        tmp_path,
        review("FAIL — 3 blocking, 1 non-blocking"),
        "🤖 fix: fixed all three.",
        review("FAIL — 1 blocking, 0 non-blocking (follow-up review)"),
        review("PASS — 0 blocking, 1 non-blocking (follow-up review)"),
        review("FAIL — 9 blocking, 0 non-blocking (follow-up review)"),
    )
    assert out["status"] == "PASS"
    assert out["values"] == {"Rounds until PASS": 3, "Blocking per round": 4 / 3}


def test_a_pr_without_a_pass_gets_no_pass(tmp_path: Path) -> None:
    """Review focus 4: an escalated merge still counts its rounds."""
    out = rounds(
        tmp_path,
        review("FAIL — 2 blocking, 0 non-blocking"),
        review("FAIL — 2 blocking, 0 non-blocking (follow-up review)"),
    )
    assert out == {
        "status": "no PASS",
        "values": {"Rounds until PASS": 2, "Blocking per round": 2.0},
    }


def test_a_pr_without_a_verdict_line_has_no_data(tmp_path: Path) -> None:
    """Such as a review from before craft 2.9.0, with a bare PASS."""
    out = rounds(tmp_path, review("PASS"), "Looks good.")
    assert out == NO_DATA


def test_a_pr_without_comments_has_no_data(tmp_path: Path) -> None:
    """An empty comment list."""
    assert rounds(tmp_path) == NO_DATA


def test_a_quoted_verdict_line_is_not_a_round(tmp_path: Path) -> None:
    """Only a line that holds only the verdict counts, at most one per comment."""
    out = rounds(
        tmp_path,
        review("FAIL — 1 blocking, 0 non-blocking"),
        "The review said `FAIL — 1 blocking, 0 non-blocking`, fixed now.",
        "> FAIL — 1 blocking, 0 non-blocking\n\nFixed.",
        review("PASS — 0 blocking, 0 non-blocking (follow-up review)"),
    )
    assert out["values"]["Rounds until PASS"] == 2  # noqa: PLR2004


def test_one_comment_counts_once(tmp_path: Path) -> None:
    """A comment that holds two verdict lines counts its last one."""
    body = "FAIL — 4 blocking, 0 non-blocking\n\nPASS — 0 blocking, 0 non-blocking"
    out = rounds(tmp_path, body)
    assert out["values"] == {"Rounds until PASS": 1, "Blocking per round": 0.0}
